export function getRandomNote() {

  const randomIndex =
    Math.floor(
      Math.random() *
      NOTES.length
    );

  return NOTES[
    randomIndex
  ];
}


// ==================================================
// CHART NOTE HELPER
// ==================================================

function createChartNote(
  beat,
  note,
  holdBeats
) {

  return Object.freeze({
    beat,
    note,

    /*
     * 0 for a tap. Anything more is a
     * long note the player holds down
     * for that many beats.
     */
    holdBeats:
      holdBeats || 0
  });
}


/*
 * Long notes.
 *
 * A note becomes a long note when the
 * music holds that sound, which shows
 * up as a long gap before the next
 * note. The hold ends short of the next
 * note, leaving time to move to the
 * next key.
 *
 * The charts generated from audio need
 * a bigger gap than Für Elise, whose
 * held notes come from the score and
 * are shorter.
 */
const MAX_HOLD_BEATS = 4;


function holdLength(
  beat,
  nextBeat,
  minGapBeats,
  releaseGapBeats
) {
  const gap =
    nextBeat - beat;


  if (
    !Number.isFinite(gap) ||
    gap < minGapBeats
  ) {
    return 0;
  }


  return Math.min(
    gap - releaseGapBeats,
    MAX_HOLD_BEATS
  );
}


// ==================================================
// CHART HELPER
// ==================================================

/*
 * Converts a list of [beat, note] pairs
 * into a frozen chart.
 *
 * The charts below were generated from
 * the audio by tools/generate-charts.py:
 *
 * - Notes are placed on beats and half
 *   beats where the track has a real hit,
 *   strongest hits first, so quiet parts
 *   of a song get fewer notes.
 * - Each note's pitch is the strongest
 *   pitch heard in the track at that
 *   moment, limited to the song's key so
 *   whatever the player plays fits the
 *   music, and kept close to the note
 *   before it.
 * - Medium contains every Easy note and
 *   Hard contains every Medium note.
 * - On Hard, a half-beat gap is always
 *   followed by at least a full beat:
 *   quick notes come in pairs, not
 *   streams.
 * - Notes with a long gap after them
 *   become long notes to hold down.
 */
function buildChart(
  pairs
) {
  return Object.freeze(
    pairs.map(
      ([beat, note], index) =>
        createChartNote(
          beat,
          note,
          holdLength(
            beat,

            index + 1 < pairs.length
              ? pairs[index + 1][0]
              : Infinity,

            3,
            0.75
          )
        )
    )
  );
}


