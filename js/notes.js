/*
 * Converts the measure list into beat
 * positions:
 *
 * melody – what the player plays
 * left   – backing piano
 * drums  – kick on each measure, hi-hat
 *          on the other two eighth notes
 */
function buildScore(
  form,
  measures,
  beatsPerMeasure
) {
  const melody = [];
  const left = [];
  const drums = [];

  form.forEach(
    (measureName, index) => {
      const measure =
        measures[measureName];

      const measureStart =
        1 + index * beatsPerMeasure;

      const toBeat =
        (sixteenth) =>
          measureStart + sixteenth / 2;

      measure.melody.forEach(
        ([sixteenth, note]) => {
          melody.push({
            beat: toBeat(sixteenth),
            note
          });
        }
      );

      measure.left.forEach(
        ([sixteenth, note]) => {
          left.push({
            beat: toBeat(sixteenth),
            note
          });
        }
      );

      drums.push(
        { beat: measureStart, sound: "kick" },
        { beat: measureStart + 1, sound: "hat" },
        { beat: measureStart + 2, sound: "hat" }
      );
    }
  );

  return { melody, left, drums };
}


/*
 * Builds a chart from the melody.
 *
 * keep(note, tiles) chooses which melody
 * notes become tiles, given the tiles
 * chosen so far. The melody notes
 * between one tile and the next are
 * stored as that tile's fills.
 */
function buildMelodyChart(
  melody,
  keep
) {
  const tiles = [];

  melody.forEach(
    (note) => {
      if (keep(note, tiles)) {
        tiles.push(note);
      }
    }
  );

  return Object.freeze(
    tiles.map(
      (tile, index) => {
        const nextBeat =
          index + 1 < tiles.length
            ? tiles[index + 1].beat
            : Infinity;

        const fills =
          melody
            .filter(
              (note) =>
                note.beat > tile.beat &&
                note.beat < nextBeat
            )
            .map(
              (note) =>
                Object.freeze({ ...note })
            );

        /*
         * The melody moves on at the next
         * melody note, not the next tile,
         * so a held note stops there.
         */
        const nextMelodyBeat =
          fills.length > 0
            ? fills[0].beat
            : nextBeat;


        return Object.freeze({
          beat: tile.beat,
          note: tile.note,

          holdBeats:
            holdLength(
              tile.beat,
              nextMelodyBeat,
              1.5,
              0.5
            ),

          fills: Object.freeze(fills)
        });
      }
    )
  );
}


